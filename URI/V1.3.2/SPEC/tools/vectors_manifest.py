#!/usr/bin/env python3
"""Generate or verify vectors.manifest.json.

Every byte count and SHA-256 in a manifest is produced by this script and never
typed by hand, so a manifest can only ever describe the files that are actually
on disk. Regenerating an unchanged tree produces identical bytes: the output
carries no timestamp.

Use it in two ways:

  generate   python vectors_manifest.py --root PKG/rttp --out PKG/rttp \
                 --protocol rttp --file src/rttp/vectors/rttp-conformance-v1.2.6.json

  verify     python vectors_manifest.py --check PKG/rttp/vectors.manifest.json

--check exits 1 on any missing file, size change or hash change, so it can be
called from CI. Standard library only, no third-party imports.
"""

import argparse
import hashlib
import json
import os
import platform
import sys

SCHEMA = "rttp-iqa-vectors/1"

NOTE = (
    "Byte counts and SHA-256 values are produced by the generator named below; "
    "do not edit this file by hand. Regenerating an unchanged tree reproduces "
    "this file byte for byte. The same vector bytes are shipped in every "
    "package, so one sha256 covers all mirrors of one protocol."
)


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def entries(root, files):
    out = []
    for rel in files:
        abs_path = os.path.join(root, rel) if root else rel
        if not os.path.isfile(abs_path):
            raise SystemExit("missing vector file: " + abs_path)
        out.append({
            "path": rel.replace("\\", "/"),
            "bytes": os.path.getsize(abs_path),
            "sha256": sha256_file(abs_path),
        })
    out.sort(key=lambda item: item["path"])
    return out


def command_line():
    return "python vectors_manifest.py --check vectors.manifest.json"


def build(protocol, files):
    manifest = {
        "schema": SCHEMA,
        "generated_by": "SPEC/tools/vectors_manifest.py",
        "generated_with": "python %s on %s" % (
            platform.python_version(), platform.system().lower()),
        "how_to_verify": command_line(),
        "files": files,
        "note": NOTE,
    }
    if protocol:
        manifest["protocol"] = protocol
    return manifest


def write_manifest(out_dir, manifest):
    path = os.path.join(out_dir, "vectors.manifest.json")
    text = json.dumps(manifest, indent=2, ensure_ascii=True) + "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return path


def check(path):
    with open(path, "r", encoding="utf-8") as handle:
        manifest = json.load(handle)
    base = os.path.dirname(os.path.abspath(path))
    bad = 0
    for item in manifest.get("files", []):
        target = os.path.join(base, item["path"])
        if not os.path.isfile(target):
            print("MISSING  " + item["path"])
            bad += 1
            continue
        size = os.path.getsize(target)
        digest = sha256_file(target)
        if size != item["bytes"] or digest != item["sha256"]:
            print("MISMATCH " + item["path"])
            print("         manifest %d bytes / %s" % (item["bytes"], item["sha256"]))
            print("         on disk  %d bytes / %s" % (size, digest))
            bad += 1
        else:
            print("ok       " + item["path"] + "  %d bytes  %s" % (size, digest[:16]))
    if bad:
        print("FAIL: %d of %d entries do not match" % (bad, len(manifest.get("files", []))))
        return 1
    print("PASS: all %d entries match" % len(manifest.get("files", [])))
    return 0


def main(argv):
    parser = argparse.ArgumentParser(description="vectors manifest generator / checker")
    parser.add_argument("--root", default=None, help="directory the paths are relative to")
    parser.add_argument("--out", default=None, help="directory to write vectors.manifest.json into")
    parser.add_argument("--protocol", default=None, help="rttp or iqa (optional)")
    parser.add_argument("--file", action="append", default=[], help="vector file, relative to --root; repeatable")
    parser.add_argument("--check", default=None, help="verify an existing vectors.manifest.json")
    args = parser.parse_args(argv)

    if args.check:
        return check(args.check)

    if not args.file:
        print("nothing to do: pass --file ... or --check ...", file=sys.stderr)
        return 2

    out_dir = args.out or args.root or "."
    manifest = build(args.protocol, entries(args.root, args.file))
    path = write_manifest(out_dir, manifest)
    print("wrote " + path)
    for item in manifest["files"]:
        print("  %s  %d bytes  %s" % (item["path"], item["bytes"], item["sha256"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
